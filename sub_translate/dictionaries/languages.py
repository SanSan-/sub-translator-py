def get_code(desired_lang: str | None) -> str | None:
    if not desired_lang:
        return None
    desired_lang = desired_lang.lower()
    if desired_lang in LANGS:
        return desired_lang
    for key, value in LANGS.items():
        if isinstance(value, str) and value.lower() == desired_lang:
            return key
    return None


def is_supported(desired_lang: str | None) -> bool:
    return bool(get_code(desired_lang))


